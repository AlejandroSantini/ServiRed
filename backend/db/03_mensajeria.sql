-- =====================================================================
CREATE TABLE IF NOT EXISTS mensaje (
  id_mensaje      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_solicitud    integer       NOT NULL,
  id_prestador    integer       NOT NULL,                  -- identifica la conversación (solicitud, prestador)
  id_remitente    integer       NOT NULL REFERENCES usuario,
  id_destinatario integer       NOT NULL REFERENCES usuario,
  texto           varchar(1000) NOT NULL CHECK (length(trim(texto)) > 0),   -- RN-M02
  fecha           timestamptz   NOT NULL,
  leido           boolean       NOT NULL DEFAULT false,
  -- RN-M01: la conversación es entre el cliente y un prestador destinatario de la solicitud.
  CONSTRAINT fk_mensaje_conversacion FOREIGN KEY (id_solicitud, id_prestador) REFERENCES solicitud_destinatario,
  CONSTRAINT ck_mensaje_participantes CHECK (id_remitente <> id_destinatario AND id_prestador IN (id_remitente, id_destinatario))
);
CREATE INDEX IF NOT EXISTS ix_mensaje_conversacion ON mensaje (id_solicitud, id_prestador, fecha);
