CREATE TABLE IF NOT EXISTS estado_comision (
  id_estado smallint PRIMARY KEY,
  nombre    varchar(30) NOT NULL UNIQUE
);
INSERT INTO estado_comision VALUES (1, 'Pendiente'), (2, 'Liquidada') ON CONFLICT DO NOTHING;

-- RN-K01: porcentaje general (id_categoria nulo) o por categoría.
CREATE TABLE IF NOT EXISTS tasa_comision (
  id_tasa             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_categoria        integer      REFERENCES categoria_oficio,
  porcentaje          numeric(5,2) NOT NULL CHECK (porcentaje BETWEEN 0 AND 100),
  fecha_actualizacion timestamptz  NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_tasa_categoria ON tasa_comision (id_categoria) WHERE id_categoria IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uk_tasa_general ON tasa_comision ((id_categoria IS NULL)) WHERE id_categoria IS NULL;

CREATE TABLE IF NOT EXISTS comision (
  id_comision       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_presupuesto    integer       NOT NULL REFERENCES presupuesto,
  id_estado         smallint      NOT NULL REFERENCES estado_comision,
  porcentaje        numeric(5,2)  NOT NULL,
  monto             numeric(12,2) NOT NULL CHECK (monto >= 0),
  fecha_registro    timestamptz   NOT NULL,
  fecha_liquidacion timestamptz,
  CONSTRAINT uk_comision_presupuesto UNIQUE (id_presupuesto),                         -- RN-K02
  CONSTRAINT ck_comision_liquidacion CHECK (id_estado = 1 OR fecha_liquidacion IS NOT NULL)   -- RN-K03
);

-- ---------- Iteración 8 ----------
CREATE TABLE IF NOT EXISTS plan_visibilidad (
  id_plan       smallint PRIMARY KEY,
  nombre        varchar(30)   NOT NULL UNIQUE,
  precio        numeric(12,2) NOT NULL CHECK (precio >= 0),
  duracion_dias smallint      NOT NULL CHECK (duracion_dias > 0),
  prioridad     smallint      NOT NULL                                -- RN-D02
);
INSERT INTO plan_visibilidad VALUES (1, 'Verificado', 5000, 30, 1), (2, 'Premium', 12000, 30, 2) ON CONFLICT DO NOTHING;

CREATE TABLE IF NOT EXISTS suscripcion (
  id_suscripcion     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_prestador       integer       NOT NULL REFERENCES prestador,
  id_plan            smallint      NOT NULL REFERENCES plan_visibilidad,
  fecha_contratacion timestamptz   NOT NULL,
  fecha_inicio       timestamptz   NOT NULL,
  fecha_fin          timestamptz   NOT NULL,
  monto              numeric(12,2) NOT NULL CHECK (monto >= 0),        -- RN-D03: cobrado fuera del sistema
  CONSTRAINT ck_suscripcion_periodo CHECK (fecha_fin > fecha_inicio)
);
CREATE INDEX IF NOT EXISTS ix_suscripcion_prestador ON suscripcion (id_prestador, fecha_fin);

CREATE TABLE IF NOT EXISTS visita_perfil (
  id_visita    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_prestador integer     NOT NULL REFERENCES prestador,
  id_visitante integer     REFERENCES usuario,
  fecha        timestamptz NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_visita_prestador ON visita_perfil (id_prestador, fecha);

