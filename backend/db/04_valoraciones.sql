CREATE TABLE IF NOT EXISTS resena (
  id_resena      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_orden       integer      NOT NULL REFERENCES orden_servicio,
  id_estado      smallint     NOT NULL REFERENCES estado_resena,
  puntaje        smallint     NOT NULL CHECK (puntaje BETWEEN 1 AND 5),    -- RN-V02
  comentario     varchar(500),                                           -- RN-V02
  fecha_feedback timestamptz  NOT NULL,
  CONSTRAINT uk_resena_orden UNIQUE (id_orden)                            -- RN-V01: una reseña por orden
);
CREATE INDEX IF NOT EXISTS ix_resena_estado ON resena (id_estado);

-- RN-V04: la reseña es inmutable; solo puede cambiar su estado (moderación).
CREATE OR REPLACE FUNCTION fn_resena_inmutable() RETURNS trigger AS $$
BEGIN
  IF (NEW.id_orden, NEW.puntaje, NEW.comentario, NEW.fecha_feedback)
     IS DISTINCT FROM (OLD.id_orden, OLD.puntaje, OLD.comentario, OLD.fecha_feedback) THEN
    RAISE EXCEPTION 'Una reseña enviada no se puede editar (RN-V04)';
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS tg_resena_inmutable ON resena;
CREATE TRIGGER tg_resena_inmutable BEFORE UPDATE ON resena FOR EACH ROW EXECUTE FUNCTION fn_resena_inmutable();

CREATE TABLE IF NOT EXISTS denuncia (
  id_denuncia           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_resena             integer     NOT NULL REFERENCES resena,
  id_prestador          integer     NOT NULL REFERENCES prestador,
  id_administrador      integer     REFERENCES administrador,            -- nulo hasta resolver
  id_estado             smallint    NOT NULL REFERENCES estado_denuncia,
  id_motivo             smallint    NOT NULL REFERENCES motivo_denuncia,
  detalle               varchar(1000),
  fecha_denuncia        timestamptz NOT NULL,
  fecha_resolucion      timestamptz,
  comentario_resolucion varchar(1000),
  -- RN-V08: la resolución registra administrador, fecha y comentario.
  CONSTRAINT ck_denuncia_resolucion CHECK (
    id_estado = 1 OR (id_administrador IS NOT NULL AND fecha_resolucion IS NOT NULL AND comentario_resolucion IS NOT NULL))
);
-- RN-V05: una sola denuncia pendiente por reseña.
CREATE UNIQUE INDEX IF NOT EXISTS uk_denuncia_pendiente ON denuncia (id_resena) WHERE id_estado = 1;
CREATE INDEX IF NOT EXISTS ix_denuncia_estado ON denuncia (id_estado);
