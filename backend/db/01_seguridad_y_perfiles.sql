-- =====================================================================
-- ServiRed (SRV) – Esquema PostgreSQL
-- Iteración 1 (perfiles y registro) + Módulo de seguridad
-- Convención: snake_case en la base, camelCase en el código.
-- Herencia: una tabla por subclase (cliente, prestador, administrador)
-- cuya PK es también FK a usuario. Estados: tablas de catálogo (ítem 4.5).
-- =====================================================================

-- ---------- Catálogos ----------
CREATE TABLE IF NOT EXISTS estado_usuario (
  id_estado  smallint PRIMARY KEY,
  nombre     varchar(30) NOT NULL UNIQUE
);
INSERT INTO estado_usuario (id_estado, nombre) VALUES (1, 'Activo'), (2, 'Bloqueado'), (3, 'Baja')
ON CONFLICT (id_estado) DO NOTHING;

CREATE TABLE IF NOT EXISTS criticidad (
  id_criticidad smallint PRIMARY KEY,
  nombre        varchar(20) NOT NULL UNIQUE
);
INSERT INTO criticidad (id_criticidad, nombre) VALUES (1, 'Baja'), (2, 'Media'), (3, 'Alta')
ON CONFLICT (id_criticidad) DO NOTHING;

CREATE TABLE IF NOT EXISTS zona (
  id_zona integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre  varchar(80) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS categoria_oficio (
  id_categoria integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre       varchar(80) NOT NULL UNIQUE
);

-- ---------- Usuarios ----------
CREATE TABLE IF NOT EXISTS usuario (
  id_usuario          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rol                 varchar(20)  NOT NULL CHECK (rol IN ('cliente', 'prestador', 'administrador')),
  nombre              varchar(80)  NOT NULL,
  apellido            varchar(80)  NOT NULL,
  email               varchar(254) NOT NULL,
  hash_contrasena     varchar(255) NOT NULL CHECK (hash_contrasena LIKE 'scrypt$%'),   -- RNF03: nunca en texto plano
  telefono_cifrado    text,                                                            -- RN-S10: AES-256-GCM
  id_estado           smallint     NOT NULL DEFAULT 1 REFERENCES estado_usuario,
  intentos_fallidos   smallint     NOT NULL DEFAULT 0 CHECK (intentos_fallidos >= 0),
  fecha_alta          timestamptz  NOT NULL DEFAULT now(),
  fecha_ultimo_acceso timestamptz,
  dvh                 char(64),                                                        -- RN-S09
  CONSTRAINT uk_usuario_email UNIQUE (email),                                          -- RN-S02
  CONSTRAINT ck_usuario_email_minusculas CHECK (email = lower(email))
);

CREATE TABLE IF NOT EXISTS cliente (
  id_usuario integer PRIMARY KEY REFERENCES usuario ON DELETE CASCADE,
  id_zona    integer NOT NULL REFERENCES zona
);

CREATE TABLE IF NOT EXISTS prestador (
  id_usuario            integer PRIMARY KEY REFERENCES usuario ON DELETE CASCADE,
  tarifa_base           numeric(12, 2) NOT NULL CHECK (tarifa_base > 0),
  descripcion           varchar(1000),
  disponibilidad        varchar(500),
  disponibilidad_activa boolean NOT NULL DEFAULT true,
  reputacion_promedio   numeric(3, 2) NOT NULL DEFAULT 0 CHECK (reputacion_promedio BETWEEN 0 AND 5)
);

CREATE TABLE IF NOT EXISTS administrador (
  id_usuario integer PRIMARY KEY REFERENCES usuario ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS prestador_zona (
  id_prestador integer REFERENCES prestador ON DELETE CASCADE,
  id_zona      integer REFERENCES zona,
  PRIMARY KEY (id_prestador, id_zona)
);

CREATE TABLE IF NOT EXISTS prestador_categoria (
  id_prestador integer REFERENCES prestador ON DELETE CASCADE,
  id_categoria integer REFERENCES categoria_oficio,
  PRIMARY KEY (id_prestador, id_categoria)
);

-- ---------- Permisos (Composite: patente = hoja, familia = compuesto) ----------
CREATE TABLE IF NOT EXISTS permiso (
  id_permiso integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo     varchar(50)  NOT NULL UNIQUE CHECK (codigo ~ '^[A-Z][A-Z0-9_]{2,49}$'),
  nombre     varchar(100) NOT NULL,
  es_familia boolean      NOT NULL,
  dvh        char(64)
);

CREATE TABLE IF NOT EXISTS permiso_hijo (
  id_padre integer REFERENCES permiso ON DELETE CASCADE,
  id_hijo  integer REFERENCES permiso ON DELETE CASCADE,
  dvh      char(64),
  PRIMARY KEY (id_padre, id_hijo),
  CHECK (id_padre <> id_hijo)
);

CREATE TABLE IF NOT EXISTS usuario_permiso (
  id_usuario integer REFERENCES usuario ON DELETE CASCADE,
  id_permiso integer REFERENCES permiso ON DELETE CASCADE,
  dvh        char(64),
  PRIMARY KEY (id_usuario, id_permiso)
);

-- ---------- Sesiones (RN-S05) ----------
CREATE TABLE IF NOT EXISTS sesion (
  id_sesion        uuid PRIMARY KEY,
  id_usuario       integer     NOT NULL REFERENCES usuario ON DELETE CASCADE,
  fecha_inicio     timestamptz NOT NULL,
  fecha_expiracion timestamptz NOT NULL CHECK (fecha_expiracion > fecha_inicio),
  fecha_cierre     timestamptz,
  ip               varchar(45)
);
CREATE INDEX IF NOT EXISTS ix_sesion_usuario_abierta ON sesion (id_usuario) WHERE fecha_cierre IS NULL;

-- ---------- Bitácora (RN-S08) ----------
-- id_usuario y email_usuario son una "foto" del momento: sin FK, para que la
-- bitácora no cambie ni se borre si se modifica el usuario o se restaura un backup.
CREATE TABLE IF NOT EXISTS bitacora (
  id_bitacora   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fecha         timestamptz  NOT NULL,
  id_usuario    integer,
  email_usuario varchar(254),
  modulo        varchar(50)  NOT NULL,
  evento        varchar(100) NOT NULL,
  descripcion   varchar(500) NOT NULL DEFAULT '',
  id_criticidad smallint     NOT NULL REFERENCES criticidad,
  ip            varchar(45),
  dvh           char(64)
);
CREATE INDEX IF NOT EXISTS ix_bitacora_fecha ON bitacora (fecha DESC);

-- La bitácora es inmutable: solo se permite completar/recalcular el dvh.
CREATE OR REPLACE FUNCTION fn_bitacora_inmutable() RETURNS trigger AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION 'La bitácora no admite borrados (RN-S08)';
  END IF;
  IF (NEW.id_bitacora, NEW.fecha, NEW.id_usuario, NEW.email_usuario, NEW.modulo, NEW.evento, NEW.descripcion, NEW.id_criticidad, NEW.ip)
     IS DISTINCT FROM
     (OLD.id_bitacora, OLD.fecha, OLD.id_usuario, OLD.email_usuario, OLD.modulo, OLD.evento, OLD.descripcion, OLD.id_criticidad, OLD.ip) THEN
    RAISE EXCEPTION 'La bitácora no admite modificaciones (RN-S08)';
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS tg_bitacora_inmutable ON bitacora;
CREATE TRIGGER tg_bitacora_inmutable BEFORE UPDATE OR DELETE ON bitacora
  FOR EACH ROW EXECUTE FUNCTION fn_bitacora_inmutable();

-- ---------- Dígito verificador vertical (RN-S09) ----------
CREATE TABLE IF NOT EXISTS digito_verificador_vertical (
  tabla         varchar(50) PRIMARY KEY,
  dvv           char(64)    NOT NULL,
  fecha_calculo timestamptz NOT NULL DEFAULT now()
);
