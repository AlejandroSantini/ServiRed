-- ---------- Solicitud de servicio ----------
CREATE TABLE IF NOT EXISTS solicitud_servicio (
  id_solicitud       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_cliente         integer      NOT NULL REFERENCES cliente,
  id_categoria       integer      NOT NULL REFERENCES categoria_oficio,
  id_zona            integer      NOT NULL REFERENCES zona,
  id_turno_preferido smallint     NOT NULL REFERENCES turno,
  id_estado          smallint     NOT NULL REFERENCES estado_solicitud,
  descripcion        varchar(1000) NOT NULL,
  direccion_cifrada  text         NOT NULL,                       -- RN-S10: AES-256-GCM
  fecha_preferida    date         NOT NULL,
  fecha_creacion     timestamptz  NOT NULL,
  fecha_limite       timestamptz  NOT NULL,
  CONSTRAINT ck_solicitud_fecha_limite CHECK (fecha_limite = fecha_creacion + interval '360 hours')   -- RN-C07: 15 días
);
CREATE INDEX IF NOT EXISTS ix_solicitud_cliente ON solicitud_servicio (id_cliente);
CREATE INDEX IF NOT EXISTS ix_solicitud_estado ON solicitud_servicio (id_estado);
CREATE INDEX IF NOT EXISTS ix_solicitud_fecha ON solicitud_servicio (fecha_creacion);

-- Lista SolicitudServicio.destinatarios → tabla intermedia con PK compuesta.
CREATE TABLE IF NOT EXISTS solicitud_destinatario (
  id_solicitud integer REFERENCES solicitud_servicio ON DELETE CASCADE,
  id_prestador integer REFERENCES prestador,
  PRIMARY KEY (id_solicitud, id_prestador)
);
CREATE INDEX IF NOT EXISTS ix_destinatario_prestador ON solicitud_destinatario (id_prestador);

-- RN-C01: como máximo 3 destinatarios por solicitud.
CREATE OR REPLACE FUNCTION fn_maximo_destinatarios() RETURNS trigger AS $$
BEGIN
  IF (SELECT count(*) FROM solicitud_destinatario WHERE id_solicitud = NEW.id_solicitud) >= 3 THEN
    RAISE EXCEPTION 'Una solicitud admite como máximo 3 prestadores (RN-C01)';
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS tg_maximo_destinatarios ON solicitud_destinatario;
CREATE TRIGGER tg_maximo_destinatarios BEFORE INSERT ON solicitud_destinatario
  FOR EACH ROW EXECUTE FUNCTION fn_maximo_destinatarios();

-- ---------- Presupuesto ----------
CREATE TABLE IF NOT EXISTS presupuesto (
  id_presupuesto        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_solicitud          integer       NOT NULL REFERENCES solicitud_servicio,
  id_prestador          integer       NOT NULL,
  id_estado             smallint      NOT NULL REFERENCES estado_presupuesto,
  monto_estimado        numeric(12,2) NOT NULL CHECK (monto_estimado > 0),           -- RN-C03
  tiempo_estimado_horas numeric(6,1)  NOT NULL CHECK (tiempo_estimado_horas > 0),    -- RN-C03
  detalle               varchar(2000),
  fecha_emision         timestamptz   NOT NULL,
  fecha_validez         date          NOT NULL,
  -- RN-C01: solo presupuestan los prestadores a los que se les mandó la solicitud.
  CONSTRAINT fk_presupuesto_destinatario FOREIGN KEY (id_solicitud, id_prestador) REFERENCES solicitud_destinatario,
  -- RN-C03: la validez es posterior a la fecha de emisión (fecha de Argentina, UTC-3).
  CONSTRAINT ck_presupuesto_validez CHECK (fecha_validez > ((fecha_emision AT TIME ZONE 'UTC') - interval '3 hours')::date)
);
-- RN-C02: un solo presupuesto Emitido por prestador y solicitud.
CREATE UNIQUE INDEX IF NOT EXISTS uk_presupuesto_vigente ON presupuesto (id_solicitud, id_prestador) WHERE id_estado = 1;
-- RN-C05: un solo presupuesto Aceptado por solicitud (evita adjudicar dos veces en pedidos simultáneos).
CREATE UNIQUE INDEX IF NOT EXISTS uk_presupuesto_aceptado ON presupuesto (id_solicitud) WHERE id_estado = 2;
CREATE INDEX IF NOT EXISTS ix_presupuesto_prestador ON presupuesto (id_prestador);
CREATE INDEX IF NOT EXISTS ix_presupuesto_estado ON presupuesto (id_estado);

-- ---------- Orden de servicio ----------
CREATE TABLE IF NOT EXISTS orden_servicio (
  id_orden                 integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_presupuesto           integer     NOT NULL REFERENCES presupuesto,
  id_turno                 smallint    NOT NULL REFERENCES turno,
  id_estado                smallint    NOT NULL REFERENCES estado_orden_servicio,
  fecha_programada         date        NOT NULL,
  fecha_inicio_real        timestamptz,
  fecha_fin_real           timestamptz,
  fecha_cierre             timestamptz,
  cerrada_sin_confirmacion boolean     NOT NULL DEFAULT false,                         -- RN-C11
  motivo_interrupcion      varchar(500),
  CONSTRAINT uk_orden_presupuesto UNIQUE (id_presupuesto),                             -- presupuesto 1 : 0..1 orden
  CONSTRAINT ck_orden_fin CHECK (fecha_fin_real IS NULL OR fecha_fin_real >= fecha_inicio_real),   -- RN-C09
  CONSTRAINT ck_orden_interrupcion CHECK (id_estado <> 3 OR motivo_interrupcion IS NOT NULL)        -- RN-C10
);
CREATE INDEX IF NOT EXISTS ix_orden_estado ON orden_servicio (id_estado);
CREATE INDEX IF NOT EXISTS ix_orden_fecha ON orden_servicio (fecha_programada, id_turno);

-- ---------- Notificaciones (RF11, RN-C13) ----------
CREATE TABLE IF NOT EXISTS notificacion (
  id_notificacion integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario      integer      NOT NULL REFERENCES usuario ON DELETE CASCADE,
  mensaje         varchar(300) NOT NULL,
  entidad         varchar(30),
  id_entidad      integer,
  fecha           timestamptz  NOT NULL,
  leida           boolean      NOT NULL DEFAULT false
);
CREATE INDEX IF NOT EXISTS ix_notificacion_usuario ON notificacion (id_usuario, leida);

-- ---------- Historial de cambios de estado (RN-C13, RNF06) ----------
CREATE TABLE IF NOT EXISTS cambio_estado (
  id_cambio          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entidad            varchar(30) NOT NULL,      -- solicitud, presupuesto, orden, resena, denuncia
  id_entidad         integer     NOT NULL,
  id_estado_anterior smallint,                  -- null = estado inicial
  id_estado_nuevo    smallint    NOT NULL,
  fecha              timestamptz NOT NULL,
  observacion        varchar(1000)
);
CREATE INDEX IF NOT EXISTS ix_cambio_estado_entidad ON cambio_estado (entidad, id_entidad);
